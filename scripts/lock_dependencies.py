"""Refresh installed-version locks from official PyPI release hashes. Maintenance only."""
from concurrent.futures import ThreadPoolExecutor
from importlib import metadata
import json
from pathlib import Path
import urllib.request

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def closure(names):
    found = {}
    while names:
        name = canonicalize_name(names.pop())
        if name in found:
            continue
        dist = metadata.distribution(name)
        found[name] = dist.version
        for text in dist.requires or []:
            requirement = Requirement(text)
            if requirement.marker is None or requirement.marker.evaluate({'extra': ''}):
                names.append(requirement.name)
    return found


def hashes(item):
    name, version = item
    url = f'https://pypi.org/pypi/{name}/{version}/json'
    with urllib.request.urlopen(url, timeout=60) as response:
        release = json.load(response)
    values = sorted({file['digests']['sha256'] for file in release['urls']})
    if not values:
        raise RuntimeError(f'No release hashes for {name}=={version}')
    return name, values


def main():
    roots = [Requirement(line).name for line in (ROOT/'requirements.txt').read_text().splitlines()
             if line.strip() and not line.startswith('#')]
    runtime = closure(roots)
    build = closure(['pyinstaller', 'setuptools'])
    build.update(runtime)
    with ThreadPoolExecutor(max_workers=6) as pool:
        sha = dict(pool.map(hashes, build.items()))
    for filename, versions in [('requirements-win-x64.lock', runtime), ('requirements-build-win-x64.lock', build)]:
        lines = ['# Windows x64 / CPython 3.12; exact versions, hashes from official PyPI.',
                 '# Generated by scripts/lock_dependencies.py; do not silently upgrade.']
        for name, version in sorted(versions.items()):
            lines.append(f'{name}=={version} \\')
            values = sha[name]
            for index, value in enumerate(values):
                lines.append('    --hash=sha256:' + value + (' \\' if index < len(values)-1 else ''))
        (ROOT/filename).write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print(f'Locked runtime={len(runtime)}, build={len(build)}')


if __name__ == '__main__':
    main()
